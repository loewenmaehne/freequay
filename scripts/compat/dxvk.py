#!/usr/bin/env python3
"""Freequay: turns the app profiles of current DXVK into compat/dxvk.txt.

DXVK keeps a table of game executables (regular expressions) with options in
src/util/config/config.cpp. CodeWeavers' DXVK 1.10.3 has the table from 2022; this takes the
current one and keeps the options 1.10.3 knows. The rules pass them in DXVK_CONFIG
(patches/dxvk-0003) and only matter for programs that run with the dxvk backend.

Usage: dxvk.py <config.cpp of current DXVK> <DXVK 1.10.3 source dir> [<version note>]
"""

import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import Rules, clean  # noqa: E402


class Unsupported(Exception):
    pass


def expand(pattern):
    """all strings a simple regular expression matches (literals, groups, |, ?), or Unsupported"""
    pos = 0

    def seq():
        nonlocal pos
        out = ['']
        while pos < len(pattern) and pattern[pos] not in '|)':
            c = pattern[pos]
            if c == '\\':
                if pos + 1 >= len(pattern):
                    raise Unsupported(pattern)
                alts = [pattern[pos + 1]]
                if alts[0].isalnum() and alts[0] not in 'x':
                    raise Unsupported(pattern)  # \d, \w, \s ...
                pos += 2
            elif c == '(':
                pos += 1
                if pattern.startswith('?:', pos):
                    pos += 2
                alts = alt()
                if pos >= len(pattern) or pattern[pos] != ')':
                    raise Unsupported(pattern)
                pos += 1
            elif c in '.*+[]{}^$':
                raise Unsupported(pattern)
            else:
                alts = [c]
                pos += 1
            if pos < len(pattern) and pattern[pos] == '?':
                alts = alts + ['']
                pos += 1
            out = [a + b for a in out for b in alts]
            if len(out) > 64:
                raise Unsupported(pattern)
        return out

    def alt():
        nonlocal pos
        out = seq()
        while pos < len(pattern) and pattern[pos] == '|':
            pos += 1
            out += seq()
        return out

    result = alt()
    if pos != len(pattern):
        raise Unsupported(pattern)
    return result


def tails(regex):
    """exe: keys for a DXVK profile regex"""
    if not regex.endswith('$'):
        raise Unsupported(regex)
    keys = []
    for s in expand(regex[:-1]):
        if not s.lower().endswith('.exe'):
            raise Unsupported(regex)
        keys.append('exe:' + s)
    return keys


def known_options(src):
    out = set()
    for root, _, files in os.walk(os.path.join(src, 'src')):
        for fn in files:
            if fn.endswith(('.cpp', '.h')):
                text = open(os.path.join(root, fn), encoding='utf-8', errors='replace').read()
                out.update(re.findall(r'getOption<[^>]+>\s*\(\s*"([a-zA-Z0-9_.]+)"', text))
    return out


def main():
    config, old_src = sys.argv[1], sys.argv[2]
    note = sys.argv[3] if len(sys.argv) > 3 else ''
    text = open(config, encoding='utf-8').read()
    table = text[text.index('g_profiles = {'):text.index('g_deckProfiles')]
    known = known_options(old_src)
    rules = Rules()
    entry = re.compile(r'((?:/\*.*?\*/\s*)*)\{\s*R"\((.*?)\)",\s*\{\{(.*?)\}\}\s*\}', re.S)
    stats = {'profiles': 0, 'kept': 0, 'regex': 0, 'options': 0}
    for m in entry.finditer(table):
        comment, regex, body = m.groups()
        stats['profiles'] += 1
        opts = re.findall(r'\{\s*"([^"]+)"\s*,\s*"([^"]*)"\s*\}', body)
        keep = [(k, v) for k, v in opts if k in known]
        title = clean(re.sub(r'/\*|\*/|\*', ' ', comment))
        try:
            keys = tails(regex)
        except Unsupported:
            stats['regex'] += 1
            continue
        if not keep:
            stats['options'] += 1
            continue
        stats['kept'] += 1
        for key in keys:
            rules.add(key, 'env=DXVK_CONFIG=' + '; '.join(f'{k} = {v}' for k, v in keep))
            if title:
                rules.note(key, 'DXVK: ' + title)
            dropped = [k for k, _ in opts if k not in known]
            if dropped:
                rules.note(key, 'not taken: DXVK options that 1.10.3 does not know: ' + ', '.join(dropped))
    out = rules.write('dxvk', [
        'Freequay: game profiles from DXVK (github.com/doitsujin/dxvk, src/util/config/config.cpp),',
        f'as of {note}, license zlib (Copyright Philip Rebohle and contributors).',
        'Only options CodeWeavers\' DXVK 1.10.3 knows; they only take effect with backend=dxvk.',
        'Generated by scripts/compat/dxvk.py, do not edit by hand.',
    ])
    print(f'{out}: {stats["kept"]} of {stats["profiles"]} profiles; {stats["regex"]} with too complex a pattern, '
          f'{stats["options"]} only with options 1.10.3 does not know')


if __name__ == '__main__':
    main()
