"""Freequay: shared helpers for the importers that turn open sources into rule files (compat/)."""

import os
import re

COMPAT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'compat')
COMPAT = os.path.normpath(COMPAT)

# directives the runtime (ntdll) and the setup tool (freequay fix) understand
RUNTIME = ('backend', 'env', 'dll', 'args', 'argdel', 'exe')
SETUP = ('verb', 'reg', 'winver')

# Windows versions winetricks knows as verbs; freequay fix sets them per program
WINVER = {'win11', 'win10', 'win81', 'win8', 'win7', 'vista', 'win2003', 'winxp', 'win2k', 'winme', 'win98', 'win95'}


def clean(text):
    """one line, no tabs, for rule values and notes"""
    return re.sub(r'\s+', ' ', str(text)).strip()


class Rules:
    """Rules of one source, collected per key and written in a stable order."""

    def __init__(self):
        self.rules = {}   # key -> list of directives
        self.notes = {}   # key -> list of notes
        self.titles = {}  # appid -> title

    def add(self, key, directive):
        name = directive.split('=', 1)[0]
        assert name in RUNTIME + SETUP, directive
        assert '\t' not in directive and '\n' not in directive, directive
        lst = self.rules.setdefault(key, [])
        if directive not in lst:
            lst.append(directive)

    def note(self, key, text):
        text = clean(text)
        lst = self.notes.setdefault(key, [])
        if text and text not in lst:
            lst.append(text)

    def title(self, appid, title):
        title = clean(title)
        if title and appid not in self.titles:
            self.titles[appid] = title

    def write(self, name, header):
        path = os.path.join(COMPAT, name + '.txt')

        def order(key):
            kind, _, ident = key.partition(':')
            return (kind, int(ident) if ident.isdigit() else 0, ident.lower())

        with open(path, 'w', encoding='utf-8') as f:
            for line in header:
                f.write(('# ' + line).rstrip() + '\n')
            for key in sorted(self.rules, key=order):
                if self.rules[key]:
                    f.write(key + '\t' + '\t'.join(self.rules[key]) + '\n')
        merge_tsv('notes.tsv', name, {k: v for k, v in self.notes.items() if v})
        merge_titles(self.titles)
        return path


def merge_tsv(filename, source, notes):
    """notes.tsv: key, source, note; replaces the rows of this source"""
    path = os.path.join(COMPAT, filename)
    rows = []
    if os.path.exists(path):
        with open(path, encoding='utf-8') as f:
            rows = [l.rstrip('\n').split('\t') for l in f if l.strip() and not l.startswith('#')]
    rows = [r for r in rows if len(r) >= 3 and r[1] != source]
    for key, texts in notes.items():
        for text in texts:
            rows.append([key, source, text])
    rows.sort(key=lambda r: (r[0].split(':')[0], int(r[0].split(':')[1]) if r[0].split(':')[1].isdigit() else 0,
                             r[0], r[1]))
    with open(path, 'w', encoding='utf-8') as f:
        f.write('# Notes on the rules: key, source, text. Every row keeps the license of its source file '
                '(see the header of compat/<source>.txt). Generated by scripts/compat/.\n')
        for r in rows:
            f.write('\t'.join(r[:2] + [clean(' '.join(r[2:]))]) + '\n')


def merge_titles(titles):
    """titles.tsv: Steam app ID, title; the first title seen for an ID stays"""
    path = os.path.join(COMPAT, 'titles.tsv')
    known = {}
    if os.path.exists(path):
        with open(path, encoding='utf-8') as f:
            for l in f:
                if l.startswith('#') or '\t' not in l:
                    continue
                appid, title = l.rstrip('\n').split('\t', 1)
                known[appid] = title
    for appid, title in titles.items():
        known.setdefault(appid, title)
    with open(path, 'w', encoding='utf-8') as f:
        f.write('# Steam app ID and title, for freequay info. Generated by scripts/compat/.\n')
        for appid in sorted(known, key=lambda a: int(a) if a.isdigit() else 0):
            f.write(appid + '\t' + known[appid] + '\n')
